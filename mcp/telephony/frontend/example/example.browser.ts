import { test, expect } from "@playwright/test";
test("example loads SDK client and supports outgoing/incoming calls on desktop and mobile", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByRole("button", { name: "Call test line" })).toBeEnabled();
  const cold = await page.evaluate(() => (window as any).example.loadMS);
  const warm = await page.evaluate(() => (window as any).example.warmLoad());
  console.log(JSON.stringify({ coldLoadMS: cold, cachedLoadMS: Math.round(warm) }));
  await page.getByRole("button", { name: "Call test line" }).click();
  await expect(page.locator("#connection")).toHaveText("Audio connected");
  await page.getByRole("button", { name: "Mute", exact: true }).click();
  await expect(page.getByRole("button", { name: "Unmute" })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Reconnect", exact: true }).click();
  await expect(page.locator("#connection")).toHaveText("Audio connected");
  await expect(page.getByRole("button", { name: "Unmute" })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Key 1", exact: true }).click();
  await expect(page.locator("#status")).toHaveText("Keypad tone sent");
  await page.getByRole("button", { name: "End call", exact: true }).click();
  await expect(page.locator("#connection")).toHaveText("Ready");
  await page.getByRole("button", { name: "Simulate incoming call" }).click();
  await page.getByRole("button", { name: "Answer call", exact: true }).click();
  await expect(page.locator("#connection")).toHaveText("Audio connected");
  await page.getByRole("button", { name: "End call", exact: true }).click();
  await expect(page.locator("#connection")).toHaveText("Ready");
  await page.screenshot({ path: "frontend/.test-results/example-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "frontend/.test-results/example-mobile.png", fullPage: true });
  expect(errors).toEqual([]);
});

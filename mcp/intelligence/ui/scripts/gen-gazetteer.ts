// Generates ../../gazetteer_countries.go from the bundled Natural Earth
// countries (world-atlas 110m), so the Go side can place country and region
// entities with the same geometry the panel draws. Run: bun scripts/gen-gazetteer.ts
import { geoArea, geoCentroid } from "d3-geo";
import { feature } from "topojson-client";
import world from "world-atlas/countries-110m.json";

const fc = feature(world as any, (world as any).objects.countries) as any;
const rows: string[] = [];
for (const f of fc.features) {
  let geom = f.geometry;
  if (!geom) continue;
  // Use the largest polygon so overseas territories do not drag the point
  // into the ocean (France, United States, Norway...).
  if (geom.type === "MultiPolygon") {
    let best = geom.coordinates[0], area = -1;
    for (const p of geom.coordinates) {
      const a = geoArea({ type: "Polygon", coordinates: p } as any);
      if (a > area) { area = a; best = p; }
    }
    geom = { type: "Polygon", coordinates: best };
  }
  const [lon, lat] = geoCentroid({ type: "Feature", geometry: geom, properties: {} } as any);
  rows.push(`\t{ID: ${JSON.stringify(String(f.id ?? ""))}, Name: ${JSON.stringify(f.properties.name)}, Lat: ${lat.toFixed(3)}, Lon: ${lon.toFixed(3)}},`);
}
rows.sort((a, b) => a.localeCompare(b));
const out = `// Code generated by ui/scripts/gen-gazetteer.ts from world-atlas
// countries-110m (Natural Earth, public domain). DO NOT EDIT.

package main

var naturalEarthCountries = []gazetteerCountry{
${rows.join("\n")}
}
`;
await Bun.write(new URL("../../gazetteer_countries.go", import.meta.url), out);
console.log(`wrote ${rows.length} countries`);

package main

import (
	"reflect"
	"testing"

	tk "github.com/apteva/app-sdk/testkit"
)

func receivedPayload(t *testing.T, rec *tk.EmitRecorder) map[string]any {
	t.Helper()
	events := rec.EventsByTopic("conversation.message.received")
	if len(events) == 0 {
		t.Fatalf("no conversation.message.received; topics=%v", emittedTopics(rec))
	}
	return events[len(events)-1].Data.(map[string]any)
}

func requireFields(t *testing.T, payload map[string]any, want map[string]any) {
	t.Helper()
	for k, v := range want {
		if !reflect.DeepEqual(payload[k], v) {
			t.Errorf("%s=%#v, want %#v", k, payload[k], v)
		}
	}
}

// We were only in Cc of a message delivered to our support mailbox: the
// delivery address wins over the header To, everything is lowercase.
func TestReceivedEventCarriesEmailRoutingFields(t *testing.T) {
	rec := tk.NewEmitRecorder()
	ctx := newTestCtx(t, tk.WithEmitter(rec))
	if _, err := ingestInbound(ctx, "test-proj", inboundPayload{
		MessageID:        91001,
		Channel:          channelEmail,
		From:             "Jane Doe <Jane@Acme.COM>",
		To:               []string{"Boss <boss@other.test>"},
		CC:               []string{"mailto:Support@Agents.test", "boss@other.test"},
		MatchedRecipient: "Support@Agents.test",
		MessageIDHeader:  "<first@acme.com>",
		BodyText:         "Help please",
	}); err != nil {
		t.Fatal(err)
	}
	requireFields(t, receivedPayload(t, rec), map[string]any{
		"to_address":            "support@agents.test",
		"to_addresses":          []any{"boss@other.test", "support@agents.test"},
		"receiving_domain":      "agents.test",
		"from_address":          "jane@acme.com",
		"from_domain":           "acme.com",
		"is_reply":              false,
		"reply_to_from_address": "",
		"is_auto_generated":     false,
		"auto_generated_reason": "",
		"channel":               channelEmail,
	})
}

// is_reply is true only when the message answers one of our sent emails.
func TestReceivedEventMarksRepliesToOurOutbound(t *testing.T) {
	rec := tk.NewEmitRecorder()
	ctx := newTestCtx(t, tk.WithEmitter(rec))
	c := mustCreate(t, ctx, map[string]any{"display_name": "Jane", "channels": []any{map[string]any{"kind": "email", "value": "jane@acme.com", "is_primary": true}}})
	convoID := mkConversation(t, ctx, "test-proj", c.ID, "email")
	if _, err := ctx.AppDB().Exec(`INSERT INTO contact_activities
		(project_id, contact_id, kind, body, occurred_at, source, source_detail, conversation_id, message_id_header)
		VALUES ('test-proj', ?, 'email_sent', 'Our offer', '2026-11-24T09:00:00Z', 'messaging', ?, ?, '<out-1@agents.test>')`,
		c.ID, `{"from":"Contact@Agents.test"}`, convoID); err != nil {
		t.Fatal(err)
	}

	// References name an unknown message first, then ours.
	if _, err := ingestInbound(ctx, "test-proj", inboundPayload{
		MessageID: 91002, Channel: channelEmail, From: "jane@acme.com",
		To: []string{"contact@agents.test"}, MatchedRecipient: "contact@agents.test",
		InReplyTo: "<unknown@elsewhere>", References: []string{"<unknown@elsewhere>", "<out-1@agents.test>"},
		MessageIDHeader: "<reply-1@acme.com>", BodyText: "Yes",
	}); err != nil {
		t.Fatal(err)
	}
	requireFields(t, receivedPayload(t, rec), map[string]any{
		"is_reply": true, "reply_to_from_address": "contact@agents.test", "conversation_id": float64(convoID),
	})

	// A follow-up that only references the contact's own earlier message is
	// in the same thread but does not answer us.
	if _, err := ingestInbound(ctx, "test-proj", inboundPayload{
		MessageID: 91003, Channel: channelEmail, From: "jane@acme.com",
		To: []string{"contact@agents.test"}, MatchedRecipient: "contact@agents.test",
		InReplyTo: "<reply-1@acme.com>", MessageIDHeader: "<reply-2@acme.com>", BodyText: "Also",
	}); err != nil {
		t.Fatal(err)
	}
	requireFields(t, receivedPayload(t, rec), map[string]any{
		"is_reply": false, "reply_to_from_address": "", "conversation_id": float64(convoID),
	})
}

func TestReceivedEventFlagsAutoGeneratedMail(t *testing.T) {
	rec := tk.NewEmitRecorder()
	ctx := newTestCtx(t, tk.WithEmitter(rec))
	mustCreate(t, ctx, map[string]any{"display_name": "Jane", "channels": []any{map[string]any{"kind": "email", "value": "jane@acme.com", "is_primary": true}}})
	if _, err := ingestInbound(ctx, "test-proj", inboundPayload{
		MessageID: 91004, Channel: channelEmail, From: "jane@acme.com",
		To: []string{"contact@agents.test"}, MatchedRecipient: "contact@agents.test",
		Headers:         map[string]any{"Auto-Submitted": "auto-replied"},
		MessageIDHeader: "<ooo@acme.com>", BodyText: "I am out of office",
	}); err != nil {
		t.Fatal(err)
	}
	p := receivedPayload(t, rec)
	if p["is_auto_generated"] != true || p["auto_generated_reason"] == "" {
		t.Fatalf("is_auto_generated=%v reason=%q", p["is_auto_generated"], p["auto_generated_reason"])
	}
}

// Non-email channels keep the same shape with empty values.
func TestReceivedEventRoutingFieldsEmptyForSMS(t *testing.T) {
	rec := tk.NewEmitRecorder()
	ctx := newTestCtx(t, tk.WithEmitter(rec))
	if _, err := ingestInbound(ctx, "test-proj", inboundPayload{
		MessageID: 91005, Channel: channelSMS, From: "+12025550123",
		To: []string{"+12025550100"}, MatchedRecipient: "+12025550100", BodyText: "hi",
	}); err != nil {
		t.Fatal(err)
	}
	requireFields(t, receivedPayload(t, rec), map[string]any{
		"to_address": "", "to_addresses": []any{}, "receiving_domain": "",
		"from_address": "", "from_domain": "", "is_reply": false,
		"reply_to_from_address": "", "is_auto_generated": false, "auto_generated_reason": "",
	})
}

package main

import (
	"database/sql"
	"strings"
)

// Routing fields on conversation.message.received let triggers filter on
// which of our addresses received an email, who sent it, whether it answers
// one of our messages, and whether it is machine mail, without a CRM read
// per event. Email only; other channels get empty values so the payload
// shape stays stable.

func routingAddress(addr string) string {
	addr = strings.TrimSpace(addr)
	if len(addr) > 7 && strings.EqualFold(addr[:7], "mailto:") {
		addr = addr[7:]
	}
	return canonicalAddress(channelEmail, addr)
}

// routingAddresses normalizes and de-duplicates To + Cc, keeping order.
func routingAddresses(lists ...[]string) []string {
	out := []string{}
	seen := map[string]bool{}
	for _, list := range lists {
		for _, raw := range list {
			addr := routingAddress(raw)
			if addr == "" || seen[addr] {
				continue
			}
			seen[addr] = true
			out = append(out, addr)
		}
	}
	return out
}

// outboundReplyTargetTx reports whether the message answers one of our sent
// emails in this conversation (In-Reply-To first, then References), and the
// address we sent it from when it was recorded.
func outboundReplyTargetTx(tx *sql.Tx, pid string, convoID int64, refs []string) (bool, string, error) {
	for _, ref := range refs {
		ok, from, err := outboundReplyRefTx(tx, pid, convoID, ref)
		if ok || err != nil {
			return ok, from, err
		}
	}
	return false, "", nil
}

func outboundReplyRefTx(tx *sql.Tx, pid string, convoID int64, ref string) (bool, string, error) {
	ref = strings.TrimSpace(ref)
	if ref == "" || convoID == 0 {
		return false, "", nil
	}
	providerID := sesProviderIDFromReference(ref)
	var from string
	err := tx.QueryRow(`SELECT COALESCE(CASE WHEN json_valid(source_detail) THEN json_extract(source_detail,'$.from') END,'')
		FROM contact_activities
		WHERE project_id=? AND conversation_id=? AND kind='email_sent'
		  AND (message_id_header=? OR (?<>'' AND (message_id_header=? OR
		       (CASE WHEN json_valid(source_detail) THEN json_extract(source_detail,'$.provider_message_id') ELSE '' END)=?)))
		ORDER BY id LIMIT 1`, pid, convoID, ref, providerID, providerID, providerID).Scan(&from)
	if err == sql.ErrNoRows {
		return false, "", nil
	}
	if err != nil {
		return false, "", err
	}
	return true, routingAddress(from), nil
}

// addInboundRoutingFields adds the routing fields to a received-event payload.
func addInboundRoutingFields(tx *sql.Tx, pid string, convoID int64, body *inboundPayload, automated bool, automatedReason string, payload map[string]any) error {
	email := body.Channel == channelEmail
	toAddress, fromAddress := "", ""
	toAddresses := []string{}
	isReply, replyFrom := false, ""
	if email {
		toAddress = routingAddress(body.MatchedRecipient)
		if toAddress == "" && len(body.EnvelopeRecipients) == 1 {
			toAddress = routingAddress(body.EnvelopeRecipients[0])
		}
		toAddresses = routingAddresses(body.To, body.CC)
		fromAddress = routingAddress(body.From)
		var err error
		isReply, replyFrom, err = outboundReplyTargetTx(tx, pid, convoID, append([]string{body.InReplyTo}, body.References...))
		if err != nil {
			return err
		}
	}
	autoGenerated := email && automated
	reason := ""
	if autoGenerated {
		reason = automatedReason
	}
	payload["to_address"] = toAddress
	payload["to_addresses"] = toAddresses
	payload["receiving_domain"] = domainOf(toAddress)
	payload["from_address"] = fromAddress
	payload["from_domain"] = domainOf(fromAddress)
	payload["is_reply"] = isReply
	payload["reply_to_from_address"] = replyFrom
	payload["is_auto_generated"] = autoGenerated
	payload["auto_generated_reason"] = reason
	return nil
}
